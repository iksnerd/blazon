export type CheckCode = keyof typeof CHECKS;

export interface FindingFields {
  path: string;
  message: string;
  context?: string;
  file?: string;
  line?: number;
  /** The fix for this finding's own cause, in place of the code's */
  fix?: string;
}

/** Build a finding of a core code. The severity is the catalogue's. */
export function finding(code: CheckCode, fields: FindingFields): Finding {
  const { path, message, context, file, line, fix } = fields;
  return {
    code,
    severity: CHECKS[code].severity,
    path,
    message,
    ...(context !== undefined && { context }),
    ...(file !== undefined && { file }),
    ...(line !== undefined && { line }),
    ...(fix !== undefined && { fix }),
  };
}
