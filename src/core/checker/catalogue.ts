import type { Finding, Severity } from '../../types/index.js';

/** Where in a project a finding points. */
export type AppliesTo = 'token' | 'group' | 'asset' | 'page' | 'config' | 'project';

interface Check {
  /** The one severity this code is ever emitted with. */
  severity: Severity;
  /** What the code means, in one plain sentence. */
  summary: string;
  /** What to do about it, when a person or an agent can fix it by editing a file. */
  fix?: string;
  /** What the finding can point at. Most codes have one; `needs-review` is emitted for tokens and for assets. */
  appliesTo: readonly AppliesTo[];
  /** RFC number and section that name the code, such as '1#4'. */
  rfc: string;
  /** Basename of the manual page that names the code. */
  manual: string;
}

