import type { ParsedTokens, TokenItem } from '../../../types/index.js';
import { typographyClassName } from '../names.js';

export interface CssFormatterOptions {
  selector?: string;
  prefix?: string;
}

const HEADER = ['/**', ' * Blazon Design Tokens', ' * Auto-generated by Blazon. Do not edit directly.', ' */', ''];

// Text for inside a CSS comment: a star-slash in it would end the comment and let the rest through as CSS.
function comment(text: string): string {
  return text.replace(/\*\//g, '* /');
}

function kebab(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

/** Every custom property a token writes in theme.css: its own, then one per composite part. */
export function tokenVariables(token: TokenItem): string[] {
  return [token.cssVariable, ...Object.keys(token.parts ?? {}).map((part) => `${token.cssVariable}-${kebab(part)}`)];
}

/** Variable declarations for one token: its value, then one variable per composite part. */
function declarations(token: TokenItem, comments = true): string[] {
  const lines: string[] = [];
  if (comments && token.description) lines.push(`  /* ${comment(token.description)} */`);
  if (comments && token.deprecated) lines.push(`  /* Deprecated${typeof token.deprecated === 'string' ? `: ${comment(token.deprecated)}` : ''} */`);
  const [own, ...partVariables] = tokenVariables(token);
  lines.push(`  ${own}: ${token.value};`);
  Object.values(token.parts ?? {}).forEach((value, i) => lines.push(`  ${partVariables[i]}: ${value};`));
  return lines;
}

/** Formats resolved tokens as CSS custom properties, one commented block per top-level group. */
export function formatCssTokens(parsed: ParsedTokens, options: CssFormatterOptions = {}): string {
  const lines = [...HEADER, `${options.selector || ':root'} {`];
  const blocks = parsed.groups
    .filter((group) => group.tokens.length > 0)
    .map((group) => [`  /* ${comment(group.name)} */`, ...group.tokens.flatMap((t) => declarations(t))].join('\n'));
  lines.push(blocks.join('\n\n'), '}', '');

  // One block per resolver context, holding only what that context changes
  for (const context of parsed.contexts ?? []) {
    if (context.tokens.length === 0) continue;
    lines.push(`/* ${comment(context.modifier)}: ${comment(context.context)} */`, `${context.selector} {`, ...context.tokens.flatMap((t) => declarations(t, false)), '}', '');
  }
  return lines.join('\n');
}

/**
 * Formats one utility class per typography token, e.g. `.type-h1 { font: var(--type-h1); ... }`.
 * Returns undefined when there are no typography tokens.
 */
export function formatTypographyCss(parsed: ParsedTokens): string | undefined {
  const typography = parsed.items.filter((t) => t.type === 'typography');
  if (typography.length === 0) return undefined;

  const classes = typography.map((token) => {
    const className = typographyClassName(token.path);
    const rules = [`  font: var(${token.cssVariable});`];
    if (token.parts?.letterSpacing !== undefined) rules.push(`  letter-spacing: var(${token.cssVariable}-letter-spacing);`);
    return `.${className} {\n${rules.join('\n')}\n}`;
  });

  return [...HEADER, classes.join('\n\n'), ''].join('\n');
}
