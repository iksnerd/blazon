import type { ParsedTokens } from '../../../types/index.js';

function contextValues(parsed: ParsedTokens): Record<string, Record<string, Record<string, string | number>>> {
  const out = Object.create(null) as Record<string, Record<string, Record<string, string | number>>>;
  for (const c of parsed.contexts ?? []) {
    // No prototype at either level: a context named __proto__ is a key, not an assignment to the prototype
    (out[c.modifier] ??= Object.create(null))[c.context] = Object.assign(Object.create(null), Object.fromEntries(c.tokens.map((t) => [t.path, t.value])));
  }
  return out;
}

/**
 * JSON as the source of a JavaScript object literal. In a literal, `"__proto__": value` sets the object's prototype and
 * makes no key, so a token or group named `__proto__` is written as the computed key `["__proto__"]`, which does.
 * JSON.stringify puts every key at the start of its own line, and a string value has no raw newline.
 */
const literal = (value: unknown): string => JSON.stringify(value, null, 2).replace(/^(\s*)"__proto__":/gm, '$1["__proto__"]:');

/**
 * Formats resolved tokens into strongly-typed TypeScript
 */
export function formatTsTokens(parsed: ParsedTokens): string {
  const flatTokensObj = Object.create(null) as Record<string, string | number>;
  const cssVarsObj = Object.create(null) as Record<string, string>;

  for (const item of parsed.items) {
    flatTokensObj[item.path] = item.value;
    cssVarsObj[item.path] = item.cssVariable;
  }

  const lines: string[] = [
    '/**',
    ' * Blazon Design Tokens',
    ' * Auto-generated by Blazon. Do not edit directly.',
    ' */',
    '',
    '/** Nested design tokens object */',
    `export const tokens = ${literal(parsed.nested)} as const;`,
    '',
    '/** Flat map of token dotted path to resolved value */',
    `export const flatTokens = ${literal(flatTokensObj)} as const;`,
    '',
    '/** Per resolver modifier and context: the token values that differ from the defaults above */',
    `export const contexts = ${literal(contextValues(parsed))} as const;`,
    '',
    '/** Map of token dotted path to CSS Custom Property variable name */',
    `export const cssVariables = ${literal(cssVarsObj)} as const;`,
    '',
    'export type Tokens = typeof tokens;',
    'export type FlatTokens = typeof flatTokens;',
    'export type TokenPath = keyof FlatTokens;',
    '',
    '/**',
    ' * Retrieve a resolved token value by path',
    ' */',
    'export function getToken<P extends TokenPath>(path: P): FlatTokens[P] {',
    '  return flatTokens[path];',
    '}',
    '',
    '/**',
    ' * Retrieve a token CSS variable expression: e.g. "var(--color-primary)"',
    ' */',
    'export function getVar<P extends TokenPath>(path: P): `var(${string})` {',
    '  return `var(${cssVariables[path]})` as const;',
    '}',
    '',
    'export default tokens;',
    '',
  ];

  return lines.join('\n');
}
