import type { ContextRead } from './brand.js';
import { SHADCN_VARIABLES, type ShadcnMapping } from './derive.js';

/** The mapping as shadcn.json: the same object `theme.shadcn` of brand.json held in version 1, with two-space indent and a final newline. */
export function formatShadcnJson(mapping: ShadcnMapping): string {
  return `${JSON.stringify(mapping, null, 2)}\n`;
}

/**
 * The mapping as the CSS shadcn/ui reads: a `:root` block with each variable blazon supplies, in the default context's values, and for each
 * other context a block under that context's selector with the variables whose token the context changes. A variable nothing supplies is
 * named in the header and left out, so shadcn's own default for it stays.
 */
export function formatShadcnCss(mapping: ShadcnMapping, contexts: readonly ContextRead[]): string {
  const header = [
    '/**',
    ' * Blazon Design Tokens, as the variables shadcn/ui reads',
    ' * Auto-generated by Blazon. Do not edit directly.',
    ...(mapping.unsupplied.length > 0
      ? [' *', ` * Not supplied, so shadcn's own value stays: ${mapping.unsupplied.join(', ')}.`, " * Name a token for each in the plugin's `variables` option."]
      : []),
    ' */',
    '',
  ];
  const lines = (values: (name: (typeof SHADCN_VARIABLES)[number]) => string | undefined) =>
    SHADCN_VARIABLES.flatMap((name) => {
      const value = values(name);
      return value === undefined ? [] : [`  --${name}: ${value};`];
    });
  const blocks: (readonly [string, string[]])[] = [[':root', lines((name) => mapping.variables[name]?.value)]];
  for (const context of contexts) {
    const changed = new Map(context.tokens.map((token) => [token.path, token.value]));
    const body = lines((name) => {
      const entry = mapping.variables[name];
      return entry ? changed.get(entry.token) : undefined;
    });
    if (body.length > 0 && context.selector !== '') blocks.push([context.selector, body]);
  }
  return [...header, ...blocks.flatMap(([selector, body], index) => [...(index > 0 ? [''] : []), `${selector} {`, ...body, '}']), ''].join('\n');
}
