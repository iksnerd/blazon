import { dimensionToPx } from '../../core/assets/measure.js';
import type { AssetMeasure, AssetMeta } from '../../types/index.js';
import type { BrandRead, PressAsset } from './brand.js';
import { fileName, finding, type Finding, type Options } from './options.js';

// Which logos go to outsiders, and where in the kit each one sits. A logo goes when it is a logo and nobody has left it unchecked: its
// sidecar's `review` is not `needs-review`, and a generated logo has been reviewed. The files are copied as they are, in a folder for the
// light backgrounds and one for the dark, by what the sidecar's `background` says, else by the pair brand.json names.

export type Surface = 'light' | 'dark' | 'unstated';

/** The folder of the kit for each kind of background; the names say it to a person who has read nothing else */
export const FOLDERS: Record<Surface, string> = { light: 'on-light-backgrounds', dark: 'on-dark-backgrounds', unstated: 'background-not-stated' };

export interface Chosen {
  asset: PressAsset;
  surface: Surface;
  /** The path inside the kit, such as logos/on-light-backgrounds/blazon-graphite.svg */
  kitPath: string;
}

const isLogo = (brand: BrandRead, asset: PressAsset): boolean => asset.category === 'logos' || asset.file === brand.logo.onLight || asset.file === brand.logo.onDark;

/** The ids of the brand's logos */
export const logoIds = (brand: BrandRead): Set<string> => new Set([...brand.assets.values()].filter((asset) => isLogo(brand, asset)).map((asset) => asset.id));

/** The surface a logo is made for: its sidecar says; without that, brand.json's own pairing; else not stated. */
export function surfaceOf(asset: PressAsset, brand: Pick<BrandRead, 'logo'>): Surface {
  if (asset.meta.background) return asset.meta.background;
  if (asset.file === brand.logo.onDark) return 'dark';
  return asset.file === brand.logo.onLight ? 'light' : 'unstated';
}

/** Why a logo must not go out, or undefined when it may */
export function holdBack(asset: PressAsset): string | undefined {
  const { review, generated } = asset.meta;
  if (review?.status === 'needs-review') return `its sidecar marks it needs-review${review.note ? `: ${review.note}` : ''}`;
  if (generated && !review) return `it was generated by ${generated.by} and nobody has confirmed it: set review.status to ok once a person has checked it`;
  return undefined;
}

export function chooseLogos(brand: BrandRead, options: Pick<Options, 'logos'>): { chosen: Chosen[]; findings: Finding[] } {
  const findings: Finding[] = [];
  const pool = [...brand.assets.values()].filter((asset) => isLogo(brand, asset) && (!options.logos || options.logos.includes(asset.id)));
  pool.sort((a, b) => (a.meta.order ?? Infinity) - (b.meta.order ?? Infinity) || a.id.localeCompare(b.id));
  const chosen: Chosen[] = [];
  const taken = new Set<string>();
  for (const asset of pool) {
    const why = holdBack(asset);
    if (why) {
      findings.push(finding('logo-left-out', 'warning', asset.id, `${asset.id} is left out of the kit because ${why}`));
      continue;
    }
    const surface = surfaceOf(asset, brand);
    const base = fileName(asset.file.split('/').pop()!);
    let kitPath = `logos/${FOLDERS[surface]}/${base}`;
    // Two files of one name in one folder are told apart by their asset id, which is unique
    if (taken.has(kitPath)) kitPath = `logos/${FOLDERS[surface]}/${fileName(asset.id)}-${base}`;
    taken.add(kitPath);
    chosen.push({ asset, surface, kitPath });
  }
  if (chosen.length === 0) findings.push(finding('logo-none', 'warning', 'assets', 'no logo is ready to go in the kit, so it carries none'));
  else {
    for (const surface of ['light', 'dark'] as const)
      if (!chosen.some((item) => item.surface === surface))
        findings.push(finding('logo-no-variant', 'warning', 'logo', `no logo in the kit is made for ${surface} backgrounds, so its ${FOLDERS[surface]} folder is not there`));
    const unstated = chosen.filter((item) => item.surface === 'unstated');
    if (unstated.length > 0)
      findings.push(
        finding(
          'logo-background-unstated',
          'info',
          unstated[0]!.asset.id,
          `${unstated.map((item) => item.asset.id).join(', ')} state no background in a sidecar, so they sit in ${FOLDERS.unstated} and a reader must choose`,
        ),
      );
  }
  return { chosen, findings };
}

function measureText(measure: AssetMeasure, meta: AssetMeta): string {
  if ('units' in measure) return `${measure.units} unit${measure.units === 1 ? '' : 's'}${meta.unit ? ` (one unit is ${dimensionToPx(meta.unit)} px)` : ''}`;
  return `${measure.value} ${measure.unit}`;
}

const dimensionsText = (size: NonNullable<AssetMeta['minSize']>): string =>
  [size.width && `${dimensionToPx(size.width)} px wide`, size.height && `${dimensionToPx(size.height)} px high`].filter(Boolean).join(' and ');

/** The logos as a page of plain text: which file is for which background, and the rules its sidecar states. Only what a sidecar says. */
export function logosText(chosen: Chosen[]): string {
  const lines = ['Logos', '', 'Each logo is the original file. Use the file in the folder named for the background it goes on.', ''];
  for (const surface of ['light', 'dark', 'unstated'] as const) {
    const items = chosen.filter((item) => item.surface === surface);
    if (items.length === 0) continue;
    const heading = surface === 'unstated' ? `Background not stated (${FOLDERS[surface]}/)` : `For ${surface} backgrounds (${FOLDERS[surface]}/)`;
    lines.push(heading, '-'.repeat(heading.length), '');
    for (const { asset, kitPath } of items) {
      const { meta } = asset;
      lines.push(kitPath.split('/').pop()!);
      if (meta.description) lines.push(`  ${meta.description}`);
      if (meta.lockup) lines.push(`  Lockup: ${meta.lockup}`);
      if (meta.clearSpace) lines.push(`  Clear space on every side: ${measureText(meta.clearSpace, meta)}`);
      if (meta.minSize) lines.push(`  Smallest size: ${dimensionsText(meta.minSize)}`);
      if (meta.maxSize) lines.push(`  Largest size: ${dimensionsText(meta.maxSize)}`);
      if (meta.ink) lines.push(`  Main color: ${meta.ink}`);
      lines.push('');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}
