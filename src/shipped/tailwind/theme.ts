import type { TokenRead } from './brand.js';
import { finding, type Finding } from './options.js';

// What the plugin writes: the Tailwind v4 theme namespaces a token can fill, the `@theme` block of the tokens that fill one
// (tailwind.css) and the `@theme` block that sets each filled namespace to `initial` (tailwind-reset.css).

const HEADER = ['/**', ' * Blazon Design Tokens, as a Tailwind v4 theme', ' * Auto-generated by Blazon. Do not edit directly.', ' */', ''];

function kebab(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[_\s]+/g, '-')
    .toLowerCase();
}

interface Namespace {
  /** The prefix of the variables written: `color` for `--color-brand` */
  prefix: string;
  /** What the reset in tailwind-reset.css writes for it, and what chapter 8 names; undefined where nothing is reset */
  reset?: string;
  /** The token types and groups it takes, for chapter 8 */
  takes: string;
  /** Whether a token belongs to it; `path` is the token's path in kebab-case */
  match: (token: TokenRead, path: string[]) => boolean;
  /** Leading path words that repeat the namespace and are left out of the variable name */
  drop: string[];
  /** Words anywhere in the path that are left out too (a `family` in `font.family.sans`) */
  dropAnywhere?: boolean;
}

/** The group of a token: the first word of its path, in lower case. */
const groupOf = (token: TokenRead) => token.path.split('.')[0]!.toLowerCase();
const inGroup = (token: TokenRead, groups: string[]) => groups.includes(groupOf(token));
const lastIs = (path: string[], word: string) => path[path.length - 1] === word;
const underFontSize = (path: string[]) => /(^|-)font-sizes?(-|$)/.test(path.slice(0, -1).join('-'));

/**
 * Every Tailwind v4 theme namespace a token can fill. The order is the order of the tables in chapter 8 and of the reset file.
 * A token type with no Tailwind namespace (border, transition and typography composites, gradients, other dimensions and numbers) is not here.
 */
export const TAILWIND_NAMESPACES: readonly Namespace[] = [
  { prefix: 'color', reset: '--color-*', takes: 'every `color` token', match: (t) => t.type === 'color', drop: ['color', 'colors'] },
  {
    prefix: 'font',
    reset: '--font-*',
    takes: 'every `fontFamily` token',
    match: (t) => t.type === 'fontFamily',
    drop: ['font', 'fonts', 'family', 'families'],
    dropAnywhere: true,
  },
  {
    prefix: 'text',
    reset: '--text-*',
    takes: '`dimension` tokens under a `font-size` (or `font-sizes`) group',
    match: (t, path) => t.type === 'dimension' && underFontSize(path),
    drop: ['font', 'font-size', 'font-sizes', 'size', 'sizes'],
  },
  {
    prefix: 'font-weight',
    reset: '--font-weight-*',
    takes: 'every `fontWeight` token',
    match: (t) => t.type === 'fontWeight',
    drop: ['font', 'fonts', 'weight', 'weights', 'font-weight', 'font-weights'],
  },
  {
    prefix: 'radius',
    reset: '--radius-*',
    takes: '`dimension` tokens in a `radius` (or `radii`, `rounded`) group',
    match: (t) => t.type === 'dimension' && inGroup(t, ['radius', 'radii', 'rounded']),
    drop: ['radius', 'radii', 'rounded'],
  },
  {
    prefix: 'spacing',
    reset: '--spacing-*',
    takes: '`dimension` tokens in a `spacing` (or `space`) group',
    match: (t) => t.type === 'dimension' && inGroup(t, ['spacing', 'space']),
    drop: ['spacing', 'space'],
  },
  { prefix: 'shadow', reset: '--shadow-*', takes: 'every `shadow` token', match: (t) => t.type === 'shadow', drop: ['shadow', 'shadows', 'elevation'] },
  {
    prefix: 'ease',
    reset: '--ease-*',
    takes: 'every `cubicBezier` token',
    match: (t) => t.type === 'cubicBezier',
    drop: ['motion', 'easing', 'easings', 'ease', 'timing'],
  },
  {
    prefix: 'default-transition-duration',
    takes: 'a `duration` token whose name is `default`, as `--default-transition-duration` (no other duration has a namespace)',
    match: (t, path) => t.type === 'duration' && lastIs(path, 'default'),
    drop: [],
  },
];

function namespace(token: TokenRead): { ns: Namespace; path: string[] } | undefined {
  const path = token.path.split('.').map(kebab);
  const ns = TAILWIND_NAMESPACES.find((n) => n.match(token, path));
  return ns && { ns, path };
}

/** The variable a token writes in tailwind.css, or undefined where the token maps to no Tailwind namespace. */
export function tailwindVariable(token: TokenRead): string | undefined {
  const found = namespace(token);
  if (!found) return undefined;
  const { ns } = found;
  if (ns.prefix === 'default-transition-duration') return `--${ns.prefix}`;
  let parts = found.path;
  // the leading group word repeats the namespace (`color.neutral.900` is `--color-neutral-900`), and so does a `family` segment
  while (parts.length > 1 && ns.drop.includes(parts[0]!)) parts = parts.slice(1);
  if (ns.dropAnywhere) parts = parts.filter((part, i) => i === parts.length - 1 || !ns.drop.includes(part));
  return `--${ns.prefix}-${parts.join('-')}`;
}

/** The namespaces that at least one token of the brand fills, in the order of TAILWIND_NAMESPACES. */
export function filledNamespaces(tokens: readonly TokenRead[]): Namespace[] {
  return TAILWIND_NAMESPACES.filter((ns) => tokens.some((token) => tailwindVariable(token) !== undefined && namespace(token)?.ns === ns));
}

/**
 * The tokens that fill a namespace of TAILWIND_NAMESPACES as a Tailwind v4 `@theme` block, with the default context's values. A variable
 * named like one in theme.css (`--color-indigo`) holds the same value. A variable is written once, for the first token that maps to it.
 * Undefined when no token maps to a Tailwind namespace.
 */
export function formatTailwindTheme(tokens: readonly TokenRead[]): string | undefined {
  const seen = new Set<string>();
  const lines: string[] = [];
  for (const token of tokens) {
    const variable = tailwindVariable(token);
    if (!variable) continue;
    if (seen.has(variable)) continue;
    seen.add(variable);
    lines.push(`  ${variable}: ${token.value};`);
  }
  if (lines.length === 0) return undefined;
  return [...HEADER, '@theme {', ...lines, '}', ''].join('\n');
}

const RESET_HEADER = (resets: string[]) => [
  '/**',
  " * Blazon Design Tokens, closing Tailwind's default theme",
  ' * Auto-generated by Blazon. Do not edit directly.',
  ' *',
  ` * Removes Tailwind's default values for ${resets.join(', ')}: the namespaces this brand defines at least one token in.`,
  ' * Utilities such as rounded-xl or bg-blue-500 then generate nothing. `--color-*: initial` removes white and black too',
  ' * (bg-white, text-black), so a brand that wants them defines them. A namespace the brand has no token in is left alone.',
  ' *',
  ' * Import it after tailwindcss and before tailwind.css:',
  ' *   @import "tailwindcss";',
  ' *   @import "./tailwind-reset.css";',
  ' *   @import "./tailwind.css";',
  ' */',
  '',
];

/**
 * A `@theme` block that sets `initial` on each Tailwind namespace the brand fills, so only the brand's values remain once tailwind.css is
 * imported after it. Undefined when no token maps to a namespace.
 */
export function formatTailwindReset(tokens: readonly TokenRead[]): string | undefined {
  const resets = filledNamespaces(tokens).flatMap((ns) => (ns.reset ? [ns.reset] : []));
  if (resets.length === 0) return undefined;
  return [...RESET_HEADER(resets.map((r) => `\`${r}\``)), '@theme {', ...resets.map((r) => `  ${r}: initial;`), '}', ''].join('\n');
}

/**
 * Two tokens whose names reduce to one Tailwind variable (`color.brand` and `colors.brand`) overwrite each other, and tailwind.css keeps the
 * first. The one that comes second is an error, unless both hold one value (a semantic alias and its primitive share a name by design) or both
 * also write one CSS variable in theme.css, where the core's own check has already said so.
 */
export function collisions(tokens: readonly TokenRead[]): Finding[] {
  const owner = new Map<string, TokenRead>();
  const found: Finding[] = [];
  for (const token of tokens) {
    const variable = tailwindVariable(token);
    if (!variable) continue;
    const first = owner.get(variable);
    if (!first) {
      owner.set(variable, token);
      continue;
    }
    if (first.path === token.path || token.value === first.value) continue;
    if (token.cssVariable !== '' && token.cssVariable === first.cssVariable) continue;
    found.push(finding('variable-duplicate', 'error', token.path, `${token.path} and ${first.path} both write the CSS variable ${variable} in tailwind.css; rename one`));
  }
  return found;
}
