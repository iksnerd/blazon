import { describe, it, expect, beforeEach } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { scanAssets } from '../../../src/core/assets/scanner.js';
import type { Finding, ParsedTokens, TokenItem } from '../../../src/types/index.js';
import { tempDir } from '../../support/project';

const SVG = '<svg viewBox="0 0 10 10" xmlns="http://www.w3.org/2000/svg"><rect width="10" height="10"/></svg>';

let dir: string;
beforeEach(() => {
  dir = tempDir();
  fs.mkdirSync(path.join(dir, 'logos'));
  fs.writeFileSync(path.join(dir, 'logos/mark.svg'), SVG);
});

function sidecar(content: unknown, name = 'logos/mark.json') {
  fs.writeFileSync(path.join(dir, name), typeof content === 'string' ? content : JSON.stringify(content));
}

function scan(tokens?: ParsedTokens) {
  const problems: Finding[] = [];
  const catalog = scanAssets(dir, { tokens, problems });
  return { mark: catalog.logos[0]!, problems };
}

const spacing4: TokenItem = { path: 'spacing.4', type: 'dimension', resolvedValue: { value: 16, unit: 'px' } } as TokenItem;
const tokens = { byPath: new Map([[spacing4.path, spacing4]]) } as unknown as ParsedTokens;

describe('asset sidecars', () => {
  it('give an asset no metadata and no problem when there is none', () => {
    const { mark, problems } = scan();
    expect(mark.meta).toBeUndefined();
    expect(problems).toEqual([]);
  });

  it('read every field, and resolve a dimension alias to its value', () => {
    sidecar({
      description: 'Primary mark',
      background: 'dark',
      clearSpace: '{spacing.4}',
      minSize: { width: { value: 80, unit: 'px' }, height: { value: 2, unit: 'rem' } },
      source: { doc: 'brand-guide', locator: 'p. 12' },
      review: { status: 'ok' },
    });
    const { mark, problems } = scan(tokens);
    expect(problems).toEqual([]);
    expect(mark.meta).toEqual({
      description: 'Primary mark',
      background: 'dark',
      clearSpace: { value: 16, unit: 'px' },
      minSize: { width: { value: 80, unit: 'px' }, height: { value: 2, unit: 'rem' } },
      source: { doc: 'brand-guide', locator: 'p. 12' },
      review: { status: 'ok' },
    });
  });

  it('report needs-review as a warning on the asset, and keep the metadata', () => {
    sidecar({ background: 'light', review: { status: 'needs-review', note: 'Slide shows a different black' } });
    const { mark, problems } = scan();
    expect(mark.meta?.background).toBe('light');
    expect(problems).toEqual([{ code: 'needs-review', severity: 'warning', path: 'logos/mark', message: 'Slide shows a different black' }]);
  });

  describe('generated', () => {
    it('is read with only the tool, or with a prompt and a licence too', () => {
      sidecar({ generated: { by: 'Midjourney v7' } });
      expect(scan().mark.meta?.generated).toEqual({ by: 'Midjourney v7' });
      sidecar({ generated: { by: 'Midjourney v7', prompt: 'a lighthouse at dusk', licence: 'Midjourney commercial plan' } });
      expect(scan().mark.meta?.generated).toEqual({ by: 'Midjourney v7', prompt: 'a lighthouse at dusk', licence: 'Midjourney commercial plan' });
    });

    it.each([
      ['is not an object', 'Midjourney', /generated must be/],
      ['has no by', { prompt: 'x' }, /generated must be/],
      ['has an empty by', { by: ' ' }, /generated must be/],
      ['has a prompt that is not a string', { by: 'x', prompt: 3 }, /generated\.prompt must be a string/],
      ['has a licence that is not a string', { by: 'x', licence: true }, /generated\.licence must be a string/],
      ['has an unknown key', { by: 'x', model: 'y' }, /generated has unknown field "model"; known: by, prompt, licence/],
    ])('is an asset-sidecar-invalid error when it %s', (_name, generated, message) => {
      sidecar({ generated });
      const { mark, problems } = scan();
      expect(mark.meta).toBeUndefined();
      expect(problems).toHaveLength(1);
      expect(problems[0]).toMatchObject({ code: 'asset-sidecar-invalid', severity: 'error' });
      expect(problems[0]!.message).toMatch(message);
    });

    it('warns generated-unreviewed at the asset id when there is no review', () => {
      sidecar({ generated: { by: 'Midjourney v7' } });
      expect(scan().problems).toEqual([
        {
          code: 'generated-unreviewed',
          severity: 'warning',
          path: 'logos/mark',
          message: 'logos/mark was generated by Midjourney v7 and nobody has confirmed it: set review.status to ok once a person has checked it',
        },
      ]);
    });

    it('reports nothing when a person has marked it ok', () => {
      sidecar({ generated: { by: 'Midjourney v7' }, review: { status: 'ok', note: 'Checked by the brand team' } });
      expect(scan().problems).toEqual([]);
    });

    it('leaves needs-review to its own warning, so the asset is not reported twice', () => {
      sidecar({ generated: { by: 'Midjourney v7' }, review: { status: 'needs-review', note: 'Hands look wrong' } });
      expect(scan().problems.map((p) => p.code)).toEqual(['needs-review']);
    });

    it('does not warn about an asset that was not generated', () => {
      sidecar({ description: 'Primary mark' });
      expect(scan().problems).toEqual([]);
    });
  });

  it.each([
    ['is not valid JSON', '{ nope', /not valid JSON/],
    ['is not an object', '[1]', /must be a JSON object/],
    ['has an unknown field', { clearSpce: { value: 1, unit: 'px' } }, /unknown field "clearSpce"; known: title, traits, do, dont, description/],
    ['has a bad background', { background: 'grey' }, /background must be "light" or "dark"/],
    ['has a bad unit', { clearSpace: { value: 1, unit: 'em' } }, /clearSpace: must be \{"value"/],
    ['has a negative size', { clearSpace: { value: -1, unit: 'px' } }, /clearSpace: must be/],
    ['aliases a missing token', { clearSpace: '{spacing.99}' }, /\{spacing\.99\} is not a token/],
    ['aliases a token that is not a dimension', { clearSpace: '{color.x}' }, /clearSpace: /],
    ['has an empty minSize', { minSize: {} }, /minSize must be an object/],
    ['has a minSize height with a bad unit', { minSize: { height: { value: 24, unit: 'em' } } }, /minSize\.height: must be \{"value"/],
    ['has a negative minSize height', { minSize: { height: { value: -24, unit: 'px' } } }, /minSize\.height: must be/],
    ['has an ink that is not a color', { ink: 'navy blue' }, /ink must be a hex color/],
    ['has an ink that is a number', { ink: 7 }, /ink must be a hex color/],
    ['has an ink that aliases a missing token', { ink: '{color.nope}' }, /ink: \{color\.nope\} is not a token/],
    ['has an order that is not a number', { order: '1' }, /order must be a number, got "1"/],
    ['has an order that is not finite', '{"order": 1e999}', /order must be a number/],
    ['has extensions that are not an object', { extensions: ['x'] }, /extensions must be an object of reverse-domain keys/],
    ['has empty extensions', { extensions: {} }, /extensions must be an object of reverse-domain keys/],
    ['has an extension key with no namespace', { extensions: { contrast: {} } }, /extensions key "contrast" must be a reverse domain name/],
    ['has an extension under the dev.blazon key', { extensions: { 'dev.blazon': {}, 'bad key': 1 } }, /extensions key "dev.blazon", "bad key" must be/],
    ['has an ink that aliases a token that is not a color', { ink: '{spacing.4}' }, /ink: \{spacing\.4\} is not a color token/],
  ])('reject a sidecar that %s, as an error with no metadata', (_, content, message) => {
    sidecar(content);
    const { mark, problems } = scan(tokens);
    expect(mark.meta).toBeUndefined();
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatchObject({ code: 'asset-sidecar-invalid', severity: 'error', path: 'logos/mark.json' });
    expect(problems[0]!.message).toMatch(message);
  });

  it('read an ink as a hex color, or as the color a token alias resolves to', () => {
    sidecar({ ink: '#0B1F3A' });
    expect(scan().mark.meta?.ink).toBe('#0B1F3A');
    const navy: TokenItem = { path: 'color.navy.900', type: 'color', resolvedValue: '#0a1f44' } as TokenItem;
    const withColor = { byPath: new Map([[navy.path, navy]]) } as unknown as ParsedTokens;
    sidecar({ ink: '{color.navy.900}' });
    const { mark, problems } = scan(withColor);
    expect(problems).toEqual([]);
    expect(mark.meta?.ink).toBe('#0a1f44');
  });

  it('keep extensions as written, and an order, without reading them', () => {
    const extensions = { 'com.acme.contrast': { onDark: 7.2, checked: ['2026-10-27'] }, 'org.example.safe-zone': null };
    sidecar({ order: -1.5, extensions });
    const { mark, problems } = scan();
    expect(problems).toEqual([]);
    expect(mark.meta).toEqual({ order: -1.5, extensions });
  });

  it('sort a category by order, then by file name, whatever the file names say', () => {
    for (const [name, order] of [
      ['a', undefined],
      ['b', 2],
      ['c', 1],
      ['d', undefined],
      ['e', 1],
      ['f', 0],
    ] as const) {
      fs.writeFileSync(path.join(dir, `logos/${name}.svg`), SVG);
      if (order !== undefined) sidecar({ order }, `logos/${name}.json`);
    }
    fs.unlinkSync(path.join(dir, 'logos/mark.svg'));
    const names = (assets: { name: string }[]) => assets.map((a) => a.name);
    const catalog = scanAssets(dir, {});
    expect(names(catalog.logos)).toEqual(['f', 'c', 'e', 'b', 'a', 'd']);
    expect(names(catalog.all)).toEqual(names(catalog.logos));
  });

  it('warn about a sidecar with no image of its name', () => {
    sidecar({ background: 'light' }, 'logos/ghost.json');
    const { problems } = scan();
    expect(problems).toEqual([{ code: 'asset-sidecar-orphan', severity: 'warning', path: 'logos/ghost.json', message: expect.stringMatching(/No image of this name/) }]);
  });

  it('let one sidecar describe the same name in two formats', () => {
    fs.writeFileSync(path.join(dir, 'logos/mark.png'), Buffer.from('89504e470d0a1a0a0000000d4948445200000001000000010806000000', 'hex'));
    sidecar({ background: 'light' });
    const problems: Finding[] = [];
    const catalog = scanAssets(dir, { problems });
    expect(catalog.logos.map((a) => a.meta?.background)).toEqual(['light', 'light']);
    expect(problems).toEqual([]);
  });

  it('refuse a sidecar that is a symlink out of the assets folder', () => {
    const outside = tempDir();
    fs.writeFileSync(path.join(outside, 'secret.json'), JSON.stringify({ description: 'leaked' }));
    fs.symlinkSync(path.join(outside, 'secret.json'), path.join(dir, 'logos/mark.json'));
    const { mark, problems } = scan();
    expect(mark.meta).toBeUndefined();
    expect(problems[0]).toMatchObject({ code: 'asset-sidecar-invalid', message: 'is outside the assets folder' });
  });
});
