// Writes the copy of the operations list that the MCP package carries: mcp/ is a separate package and cannot import src/, so what it needs
// (the operations that have a tool, and the pure code that checks arguments and builds a tool) is generated into mcp/src/generated/.
// test/core/operations-mcp.test.ts fails when the files differ from what this script writes. Run it with `npm run gen:mcp`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { OPERATIONS, toolOperations } from '../src/core/operations/index.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const FROM = 'src/core/operations';
const TO = 'mcp/src/generated';
const HEADER = '// Generated by scripts/gen-mcp-operations.ts from src/core/operations. Do not edit it: change the source and run `npm run gen:mcp`.\n';

/** Sources copied as they are: the files that import nothing but each other. */
const COPIED = ['types.ts', 'check.ts', 'project.ts'];

/** The generated files, by path from the repository root. */
export async function generated(): Promise<Record<string, string>> {
  const files: Record<string, string> = {};
  for (const name of COPIED) files[`${TO}/${name}`] = fs.readFileSync(path.join(ROOT, FROM, name), 'utf8');
  files[`${TO}/operations.ts`] = `import type { Operation } from './types.js';\n\nexport const OPERATIONS: readonly Operation[] = ${JSON.stringify(toolOperations(OPERATIONS))};\n`;
  const result: Record<string, string> = {};
  for (const [file, text] of Object.entries(files)) {
    const options = (await prettier.resolveConfig(path.join(ROOT, file))) ?? {};
    result[file] = await prettier.format(HEADER + text, { ...options, parser: 'typescript' });
  }
  return result;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.join(ROOT, TO), { recursive: true });
  for (const [file, text] of Object.entries(await generated())) fs.writeFileSync(path.join(ROOT, file), text);
}
